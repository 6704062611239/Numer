#include <stdio.h>

int main() {
    int i, j;
    int A[3][3];
    int B[3];
    int A1[3][3], A2[3][3], A3[3][3];

    for(i = 0; i < 3; i++) {
        for(j = 0; j < 3; j++) {
            scanf("%d", &A[i][j]);
        }
    }

    for(i = 0; i < 3; i++) {
        scanf("%d", &B[i]);
    }

    for(i = 0; i < 3; i++) {
        for(j = 0; j < 3; j++) {
            A1[i][j] = A[i][j];
            A2[i][j] = A[i][j];
            A3[i][j] = A[i][j];
        }
    }

    for(i = 0; i < 3; i++) {
        A1[i][0] = B[i];
        A2[i][1] = B[i];
        A3[i][2] = B[i];
    }

    int detA1 =
        (A1[0][0] * A1[1][1] * A1[2][2])
      + (A1[0][1] * A1[1][2] * A1[2][0])
      + (A1[0][2] * A1[1][0] * A1[2][1])
      - (A1[0][2] * A1[1][1] * A1[2][0])
      - (A1[0][1] * A1[1][0] * A1[2][2])
      - (A1[0][0] * A1[1][2] * A1[2][1]);

    int detA2 =
        (A2[0][0] * A2[1][1] * A2[2][2])
      + (A2[0][1] * A2[1][2] * A2[2][0])
      + (A2[0][2] * A2[1][0] * A2[2][1])
      - (A2[0][2] * A2[1][1] * A2[2][0])
      - (A2[0][1] * A2[1][0] * A2[2][2])
      - (A2[0][0] * A2[1][2] * A2[2][1]);

    int detA3 =
        (A3[0][0] * A3[1][1] * A3[2][2])
      + (A3[0][1] * A3[1][2] * A3[2][0])
      + (A3[0][2] * A3[1][0] * A3[2][1])
      - (A3[0][2] * A3[1][1] * A3[2][0])
      - (A3[0][1] * A3[1][0] * A3[2][2])
      - (A3[0][0] * A3[1][2] * A3[2][1]);

    int detA =
        (A[0][0] * A[1][1] * A[2][2])
      + (A[0][1] * A[1][2] * A[2][0])
      + (A[0][2] * A[1][0] * A[2][1])
      - (A[0][2] * A[1][1] * A[2][0])
      - (A[0][1] * A[1][0] * A[2][2])
      - (A[0][0] * A[1][2] * A[2][1]);

    printf("x1 = %f\n", (float)detA1 / detA);
    printf("x2 = %f\n", (float)detA2 / detA);
    printf("x3 = %f\n", (float)detA3 / detA);
    

}
